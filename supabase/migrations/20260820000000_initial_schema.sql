create or replace function public.fabriquer_article(p_employe_id bigint, p_article_id bigint, p_nombre_crafts integer)
returns integer
language plpgsql
set search_path = ''
as $$
declare
  v_produit public.catalogue%rowtype;
  v_employe_nom text;
  v_ingredient record;
  v_quantite_produite integer;
  v_fabrication_id bigint;
  v_cout_ingredients numeric := 0;
  v_cout_ligne numeric;
begin
  if p_nombre_crafts <= 0 then raise exception 'Le nombre de crafts doit être positif'; end if;

  select employe.nom_prenom
  into v_employe_nom
  from public.employes employe
  where employe.id = p_employe_id and employe.actif;
  if v_employe_nom is null then raise exception 'Employé introuvable ou inactif'; end if;

  select catalogue.*
  into v_produit
  from public.catalogue catalogue
  where catalogue.id = p_article_id and catalogue.actif;
  if not found then raise exception 'Produit introuvable ou inactif'; end if;

  select recette.quantite_produite * p_nombre_crafts
  into v_quantite_produite
  from public.recettes_craft recette
  where recette.produit_id = p_article_id
  order by recette.id
  limit 1;
  if v_quantite_produite is null then raise exception 'Aucune recette trouvée'; end if;

  insert into public.fabrications (
    employe_id, employe_nom, produit_id, produit_nom, nombre_crafts,
    quantite_produite, cout_craft_total
  ) values (
    p_employe_id, v_employe_nom, v_produit.id, v_produit.article, p_nombre_crafts,
    v_quantite_produite, v_produit.cout_craft_po * p_nombre_crafts
  ) returning id into v_fabrication_id;

  for v_ingredient in
    select recette.ingredient_id, catalogue.article,
      recette.quantite_requise * p_nombre_crafts as quantite
    from public.recettes_craft recette
    join public.catalogue catalogue on catalogue.id = recette.ingredient_id
    where recette.produit_id = p_article_id
    order by recette.ingredient_id
  loop
    perform public.decrementer_stock(v_ingredient.ingredient_id, v_ingredient.quantite);
    v_cout_ligne := public.cout_revient_article(v_ingredient.ingredient_id) * v_ingredient.quantite;
    v_cout_ingredients := v_cout_ingredients + v_cout_ligne;
    insert into public.fabrications_ingredients (
      fabrication_id, ingredient_id, ingredient_nom, quantite_consommee,
      cout_unitaire, cout_total
    ) values (
      v_fabrication_id, v_ingredient.ingredient_id, v_ingredient.article,
      v_ingredient.quantite, public.cout_revient_article(v_ingredient.ingredient_id),
      v_cout_ligne
    );
  end loop;

  perform public.incrementer_stock(p_article_id, v_quantite_produite);
  update public.fabrications
  set cout_ingredients = v_cout_ingredients,
    cout_total = v_cout_ingredients + public.fabrications.cout_craft_total
  where public.fabrications.id = v_fabrication_id;

  insert into public.transactions (
    vendeur_id, article_id, quantite, prix_total, benefice_total, type_transaction
  ) values (
    p_employe_id, p_article_id, v_quantite_produite,
    -(v_produit.cout_craft_po * p_nombre_crafts),
    -(v_produit.cout_craft_po * p_nombre_crafts), 'Frais de Craft'
  );

  return v_quantite_produite;
end;
$$;

