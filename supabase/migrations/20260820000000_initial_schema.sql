-- Views

create view public.transactions_courantes
with (security_invoker = true) as
select transaction.*
from public.transactions transaction
join public.periodes_comptables periode on periode.id = transaction.periode_id
where periode.statut = 'ouverte';

create view public.periode_comptable_courante
with (security_invoker = true) as
select
  periode.*,
  (current_date - periode.date_debut)::integer as jours_ouverts,
  greatest(14 - (current_date - periode.date_debut), 0)::integer as jours_avant_cloture,
  current_date - periode.date_debut >= 14 as cloture_recommandee
from public.periodes_comptables periode
where periode.statut = 'ouverte';

create view public.performances_employes
with (security_invoker = true) as
select
  employe.id as employe_id,
  employe.nom_prenom,
  employe.grade,
  employe.prime_actuelle,
  coalesce(sum(transaction.prix_total) filter (where transaction.type_transaction = 'Vente'), 0)::numeric(14, 2) as ca_realise,
  coalesce(sum(transaction.benefice_total) filter (where transaction.type_transaction = 'Vente'), 0)::numeric(14, 2) as benefice_realise,
  count(transaction.id) filter (where transaction.type_transaction = 'Vente')::integer as nombre_lignes_vente,
  coalesce(sum(transaction.quantite) filter (where transaction.type_transaction = 'Vente'), 0)::integer as articles_vendus
from public.employes employe
left join public.transactions_courantes transaction on transaction.vendeur_id = employe.id
where employe.actif
group by employe.id, employe.nom_prenom, employe.grade, employe.prime_actuelle;

create view public.historique_comptable
with (security_invoker = true) as
select periode.*
from public.periodes_comptables periode
where periode.statut = 'clôturée'
order by periode.date_fin desc;

create view public.employes_actifs
with (security_invoker = true) as
select * from public.employes where actif;

create view public.catalogue_actif with (security_invoker = true) as
