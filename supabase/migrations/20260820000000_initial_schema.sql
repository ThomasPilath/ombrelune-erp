create or replace function public.cloturer_periode(
  p_date_fin date default current_date,
  p_remunerations jsonb default '[]'::jsonb
)
returns bigint
language plpgsql
set search_path = ''
as $$
declare
  periode public.periodes_comptables%rowtype;
  v_ca numeric;
  v_depenses numeric;
  v_brut numeric;
  v_taxes_calculees numeric;
  v_salaires numeric;
  v_ventes integer;
  v_achats integer;
  v_crafts integer;
  remuneration record;
begin
  select * into periode
  from public.periodes_comptables
  where statut = 'ouverte'
  for update;

  if not found then raise exception 'Aucune période comptable ouverte'; end if;
  if p_date_fin < periode.date_debut then raise exception 'Date de clôture invalide'; end if;
  if jsonb_typeof(p_remunerations) <> 'array' then
    raise exception 'Les rémunérations doivent être un tableau JSON';
  end if;
  if exists (
    select 1 from public.transactions
    where periode_id = periode.id and date_transaction > p_date_fin
  ) then
    raise exception 'Des transactions existent après la date de clôture demandée';
  end if;

  select
    coalesce(sum(prix_total) filter (where type_transaction in ('Vente', 'Vente Employé')), 0),
    coalesce(sum(abs(prix_total)) filter (
      where type_transaction = 'Achat'
         or type_transaction = 'Frais de Craft'
         or type_transaction like 'Frais : %'
    ), 0),
    count(*) filter (where type_transaction in ('Vente', 'Vente Employé')),
    count(*) filter (where type_transaction = 'Achat'),
    count(*) filter (where type_transaction = 'Frais de Craft')
  into v_ca, v_depenses, v_ventes, v_achats, v_crafts
  from public.transactions
  where periode_id = periode.id
    and date_transaction <= p_date_fin;

  v_brut := v_ca - v_depenses;
  v_taxes_calculees := round(greatest(v_brut, 0) * 0.40);
  select coalesce(sum((element->>'total_paye')::numeric), 0)
  into v_salaires
  from jsonb_array_elements(p_remunerations) element;

  update public.periodes_comptables
  set date_fin = p_date_fin,
      statut = 'clôturée',
      ca_total = v_ca,
      depenses = v_depenses,
      benefice_brut = v_brut,
      taxes = v_taxes_calculees,
      salaires_primes = v_salaires,
      benefice_net = v_brut - v_taxes_calculees,
      nombre_ventes = v_ventes,
      nombre_achats = v_achats,
      nombre_crafts = v_crafts,
      cloturee_at = now()
  where id = periode.id;

  for remuneration in
    select (element->>'employe_id')::bigint as employe_id,
           coalesce((element->>'prime')::numeric, 0) as prime,
           coalesce((element->>'total_paye')::numeric, 0) as total_paye
    from jsonb_array_elements(p_remunerations) element
  loop
    insert into public.archives_rh (
      periode_id, employe_id, employe_nom, ca_ventes, prime, total_paye
    )
    select periode.id, employe.id, employe.nom_prenom,
      coalesce(sum(transaction.prix_total), 0), remuneration.prime, remuneration.total_paye
    from public.employes employe
    left join public.transactions transaction
      on transaction.vendeur_id = employe.id
      and transaction.periode_id = periode.id
      and transaction.type_transaction in ('Vente', 'Vente Employé')
    where employe.id = remuneration.employe_id
    group by employe.id, employe.nom_prenom;
    if not found then
      raise exception 'Employé % introuvable pour l''archive RH', remuneration.employe_id;
    end if;
  end loop;

  update public.employes set prime_actuelle = 0;
  -- Le registre des tickets constitue un historique permanent. Le quota est
  -- calculé par session de jeu et ne dépend pas des périodes comptables.
  insert into public.periodes_comptables (date_debut) values (p_date_fin + 1);
  return periode.id;
end;
$$;

