create or replace function public.enregistrer_client_permit(
  p_permit_id bigint,
  p_client_id bigint,
  p_type text,
  p_status text,
  p_employe_id bigint
)
returns bigint language plpgsql security definer set search_path = '' as $$
declare permit public.client_permits%rowtype; permit_id bigint; before_state jsonb;
begin
  if p_type not in ('broomstick', 'motorcycle', 'car') then raise exception 'Type de permis invalide'; end if;
  if p_status not in ('pending', 'accepted', 'refused', 'cancelled') then raise exception 'État de permis invalide'; end if;
  if not exists (select 1 from public.clients where id = p_client_id and actif) then raise exception 'Client introuvable ou archivé'; end if;
  if not exists (select 1 from public.employes where id = p_employe_id and actif) then raise exception 'Employé introuvable ou inactif'; end if;

  if p_permit_id is null then
    insert into public.client_permits (client_id, type, status)
    values (p_client_id, p_type, p_status) returning id into permit_id;
    perform public.journaliser_action_client(p_employe_id, 'create', 'client_permit', permit_id::text,
      'permit_' || p_type, p_client_id, null, jsonb_build_object('status', p_status));
  else
    select * into permit from public.client_permits where id = p_permit_id for update;
    if not found then raise exception 'Dossier de permis introuvable'; end if;
    if permit.status = 'sold' then raise exception 'Un permis vendu ne peut pas être modifié'; end if;
    before_state := jsonb_build_object('client_id', permit.client_id, 'type', permit.type, 'status', permit.status);
    update public.client_permits set client_id = p_client_id, type = p_type, status = p_status
    where id = permit.id returning id into permit_id;
    perform public.journaliser_action_client(p_employe_id, 'update_status', 'client_permit', permit_id::text,
      'permit_' || p_type, p_client_id, before_state,
      jsonb_build_object('client_id', p_client_id, 'type', p_type, 'status', p_status));
  end if;
  return permit_id;
exception when unique_violation then
  raise exception 'Ce client possède déjà un dossier pour ce type de permis';
end;
$$;

