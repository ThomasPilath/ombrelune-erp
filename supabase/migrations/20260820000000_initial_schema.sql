create or replace function public.creer_commande(
  p_client_id bigint,
  p_employe_id bigint,
  p_date_livraison date,
  p_lignes jsonb,
  p_contenu text default null
)
returns bigint
language plpgsql
set search_path = ''
as $$
declare
  commande_id bigint;
  ligne record;
  prix_article numeric;
begin
  if jsonb_typeof(p_lignes) <> 'array' or jsonb_array_length(p_lignes) = 0 then
    raise exception 'La commande doit contenir au moins une ligne';
  end if;
  if not exists (select 1 from public.clients where id = p_client_id and actif) then
    raise exception 'Client % introuvable ou inactif', p_client_id;
  end if;
  if not exists (select 1 from public.employes where id = p_employe_id and actif) then
    raise exception 'Employé % introuvable ou inactif', p_employe_id;
  end if;

  insert into public.commandes (client_id, employe_id, date_livraison, contenu)
  values (p_client_id, p_employe_id, p_date_livraison, nullif(trim(p_contenu), ''))
  returning id into commande_id;

  for ligne in
    select (element->>'article_id')::bigint as article_id,
           (element->>'quantite')::integer as quantite,
           nullif(element->>'prix_unitaire', '')::numeric as prix_unitaire
    from jsonb_array_elements(p_lignes) element
  loop
    if ligne.quantite is null or ligne.quantite <= 0 then
      raise exception 'Chaque quantité commandée doit être strictement positive';
    end if;
    select catalogue.prix_vente into prix_article
    from public.catalogue catalogue
    where catalogue.id = ligne.article_id and catalogue.actif;
    if not found then raise exception 'Article % introuvable ou inactif', ligne.article_id; end if;

    insert into public.lignes_commandes (commande_id, article_id, quantite, prix_unitaire)
    values (commande_id, ligne.article_id, ligne.quantite, coalesce(ligne.prix_unitaire, prix_article));
  end loop;
  return commande_id;
end;
$$;

create or replace function public.changer_statut_commande(p_commande_id bigint, p_nouveau_statut text)
returns void
language plpgsql
set search_path = ''
as $$
declare
  statut_actuel text;
begin
  select statut_livraison into statut_actuel
  from public.commandes where id = p_commande_id for update;
  if statut_actuel is null then raise exception 'Commande introuvable'; end if;
  if not (
    (statut_actuel = 'En préparation' and p_nouveau_statut = 'Prêt')
    or (statut_actuel = 'Prêt' and p_nouveau_statut = 'Livré')
  ) then
    raise exception 'Transition de commande invalide';
  end if;
  update public.commandes set
    statut_livraison = p_nouveau_statut,
    date_pret = case when p_nouveau_statut = 'Prêt' then current_date else date_pret end
  where id = p_commande_id;
end;
$$;

create or replace function public.gerer_commande(
  p_commande_id bigint,
  p_employe_id bigint,
  p_action text
)
returns void
language plpgsql
set search_path = ''
as $$
declare
  commande public.commandes%rowtype;
  employe_nom text;
  prochain_statut text;
  snapshot jsonb;
begin
  select nom_prenom into employe_nom
  from public.employes where id = p_employe_id and actif;
  if employe_nom is null then raise exception 'Employé introuvable ou inactif'; end if;

  select * into commande from public.commandes where id = p_commande_id for update;
  if not found then raise exception 'Commande introuvable'; end if;

  snapshot := to_jsonb(commande) || jsonb_build_object(
    'lignes', coalesce((select jsonb_agg(to_jsonb(ligne) order by ligne.id)
      from public.lignes_commandes ligne where ligne.commande_id = commande.id), '[]'::jsonb)
  );

  if p_action = 'Préparation terminée' then
    if commande.statut_livraison <> 'En préparation' then raise exception 'Transition de commande invalide'; end if;
    prochain_statut := 'Prêt';
    update public.commandes set statut_livraison = prochain_statut, date_pret = current_date where id = commande.id;
  elsif p_action = 'Livraison' then
    if commande.statut_livraison <> 'Prêt' then raise exception 'Transition de commande invalide'; end if;
    prochain_statut := 'Livré';
    update public.commandes set statut_livraison = prochain_statut where id = commande.id;
  elsif p_action = 'Annulation' then
    if commande.statut_livraison in ('Livré', 'Annulée') then raise exception 'Cette commande ne peut plus être annulée'; end if;
    prochain_statut := 'Annulée';
    update public.commandes set statut_avant_annulation = commande.statut_livraison,
      statut_livraison = prochain_statut where id = commande.id;
  elsif p_action = 'Restauration' then
    if commande.statut_livraison <> 'Annulée' then raise exception 'Seule une commande annulée peut être restaurée'; end if;
    prochain_statut := coalesce(commande.statut_avant_annulation, 'En préparation');
    update public.commandes set statut_livraison = prochain_statut,
      statut_avant_annulation = null where id = commande.id;
  elsif p_action = 'Retour arrière' then
    prochain_statut := case commande.statut_livraison
      when 'Prêt' then 'En préparation'
      when 'Livré' then 'Prêt'
      else null
    end;
    if prochain_statut is null then raise exception 'Aucun état précédent disponible'; end if;
    update public.commandes set statut_livraison = prochain_statut,
      date_pret = case when prochain_statut = 'En préparation' then null else date_pret end
    where id = commande.id;
  elsif p_action = 'Suppression' then
    if commande.statut_livraison <> 'Annulée' then raise exception 'Une commande doit être annulée avant sa suppression'; end if;
    prochain_statut := null;
  else
    raise exception 'Action de commande invalide';
  end if;

  insert into public.commandes_journal (
    commande_id, commande_reference, employe_id, employe_nom, action,
    statut_avant, statut_apres, commande_snapshot
  ) values (
    commande.id, commande.id, p_employe_id, employe_nom, p_action,
    commande.statut_livraison, prochain_statut, snapshot
  );

  if p_action = 'Suppression' then delete from public.commandes where id = commande.id; end if;
end;
$$;

create or replace function public.valider_passage_permis(p_permis_id bigint, p_employe_id bigint, p_statut text)
returns void language plpgsql set search_path = '' as $$
begin
  if p_statut not in ('validé', 'interdit') then raise exception 'Statut de permis invalide'; end if;
