  total_vente numeric := 0;
begin
  if not exists (select 1 from public.employes where id = p_vendeur_id and actif) then
    raise exception 'Employé % introuvable ou inactif', p_vendeur_id;
  end if;
  if jsonb_typeof(p_lignes) <> 'array' or jsonb_array_length(p_lignes) = 0 then
    raise exception 'La vente doit contenir au moins une ligne';
  end if;
  if p_remise_pourcent < 0 or p_remise_pourcent > 100 then raise exception 'Remise invalide'; end if;
  if p_type_transaction not in ('Vente', 'Vente Employé') then raise exception 'Type de vente invalide'; end if;

  for ligne in
    select (element->>'article_id')::bigint article_id, (element->>'quantite')::integer quantite
    from jsonb_array_elements(p_lignes) element
    order by (element->>'article_id')::bigint
  loop
    if ligne.quantite is null or ligne.quantite <= 0 then raise exception 'Quantité de vente invalide'; end if;
    select * into article from public.catalogue where id = ligne.article_id and actif;
    if not found or article.prix_vente <= 0 then raise exception 'Article % non vendable', ligne.article_id; end if;

    -- Le supplément boussole est une majoration tarifaire et non un article physique.
    if lower(article.article) <> lower('Supplément boussole') then
      perform public.decrementer_stock(article.id, ligne.quantite);
    end if;

    total_ligne := round(article.prix_vente * ligne.quantite * (100 - p_remise_pourcent) / 100);
    cout_ligne := public.cout_revient_article(article.id) * ligne.quantite;
    insert into public.transactions (vendeur_id, article_id, quantite, prix_unitaire, prix_total, benefice_total, type_transaction)
    values (p_vendeur_id, article.id, ligne.quantite, article.prix_vente, total_ligne, total_ligne - cout_ligne, p_type_transaction);
    total_vente := total_vente + total_ligne;
  end loop;
  return total_vente;
end;
$$;

