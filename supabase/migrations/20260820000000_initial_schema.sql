create or replace function public.auditer_permis()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  v_employe_id bigint;
  v_action text;
begin
  if not old.document_sell and new.document_sell then
    v_employe_id := new.retire_par;
    v_action := 'Retrait de permis confirmé';
  elsif old.statut is distinct from new.statut then
    v_employe_id := new.valide_par;
    v_action := case new.statut when 'validé' then 'Validation de permis' when 'interdit' then 'Interdiction de permis' else 'Modification de permis' end;
  else
    return new;
  end if;
  if v_employe_id is not null then
    perform public.ecrire_journal_action(
      v_employe_id, v_action, 'permis', new.id::text,
      new.candidat || ' — ' || new.type_permis,
      jsonb_build_object('statut', old.statut, 'document_vendu', old.document_sell),
      jsonb_build_object('statut', new.statut, 'document_vendu', new.document_sell),
      jsonb_build_object('client_id', new.client_id)
    );
  end if;
  return new;
end;
$$;

