create or replace function public.incrementer_stock(p_article_id bigint, p_quantite integer)
returns void
language plpgsql
set search_path = ''
as $$
begin
  if p_quantite <= 0 then
    raise exception 'La quantité à ajouter doit être strictement positive';
  end if;

  insert into public.stocks (article_id, quantite)
  values (p_article_id, p_quantite)
  on conflict (article_id) do update
  set quantite = public.stocks.quantite + excluded.quantite,
      updated_at = now();
end;
$$;

create or replace function public.decrementer_stock(p_article_id bigint, p_quantite integer)
returns void
language plpgsql
set search_path = ''
as $$
declare
  quantite_disponible integer;
begin
  if p_quantite <= 0 then
    raise exception 'La quantité à retirer doit être strictement positive';
  end if;

  select stock.quantite
  into quantite_disponible
  from public.stocks stock
  where stock.article_id = p_article_id
  for update;

  if quantite_disponible is null then
    raise exception 'Aucun stock trouvé pour l''article %', p_article_id;
  end if;

  if quantite_disponible < p_quantite then
    raise exception 'Stock insuffisant pour l''article % : % disponible(s), % demandé(s)',
      p_article_id, quantite_disponible, p_quantite;
  end if;

  update public.stocks
  set quantite = quantite - p_quantite,
      updated_at = now()
  where article_id = p_article_id;
end;
$$;

create or replace function public.cout_revient_article(
  p_article_id bigint,
  p_articles_visites bigint[] default '{}'::bigint[]
)
returns numeric
language plpgsql
stable
set search_path = ''
as $$
declare
  article public.catalogue%rowtype;
  ingredient record;
  cout numeric := 0;
begin
  if p_article_id = any(p_articles_visites) then
    raise exception 'Cycle détecté dans la recette de l''article %', p_article_id;
  end if;

  select * into article from public.catalogue where id = p_article_id;
  if not found then
    raise exception 'Article % introuvable', p_article_id;
  end if;

  if article.prix_achat > 0 then
    return article.prix_achat;
  end if;

  cout := article.cout_craft_po;
  for ingredient in
    select recette.ingredient_id, recette.quantite_requise, recette.quantite_produite
    from public.recettes_craft recette
    where recette.produit_id = p_article_id
  loop
    cout := cout + public.cout_revient_article(
      ingredient.ingredient_id,
      array_append(p_articles_visites, p_article_id)
    ) * ingredient.quantite_requise / ingredient.quantite_produite;
  end loop;

  return round(cout, 2);
end;
$$;

