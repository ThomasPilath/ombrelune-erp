create or replace function public.enregistrer_panier(
  p_vendeur_id bigint,
  p_lignes jsonb,
  p_client_ticket_id bigint default null,
  p_retraits_permis jsonb default '[]'::jsonb
)
returns numeric language plpgsql security definer set search_path = '' as $$
declare
  session_date date := public.session_jeu();
  ticket_quantite integer;
  ticket_deja integer := 0;
  retrait record;
  permit public.client_permits%rowtype;
  article_type text;
  article_permit_type text;
  expected_permits integer;
  total numeric;
begin
  if not exists (select 1 from public.employes where id = p_vendeur_id and actif) then raise exception 'Employé introuvable ou inactif'; end if;
  if jsonb_typeof(p_lignes) <> 'array' or jsonb_array_length(p_lignes) = 0 then raise exception 'Le panier est vide'; end if;

  select coalesce(sum((element->>'quantite')::integer), 0) into ticket_quantite
  from jsonb_array_elements(p_lignes) element
  join public.catalogue article on article.id = (element->>'article_id')::bigint
  where article.type_article = 'ticket';

  if ticket_quantite > 0 then
    if ticket_quantite > 2 then raise exception 'Deux tickets maximum par client et par session'; end if;
    if p_client_ticket_id is null then raise exception 'Un client actif est obligatoire pour les tickets'; end if;
    perform pg_advisory_xact_lock(hashtextextended('ticket:' || p_client_ticket_id || ':' || session_date, 0));
    select case when ticket_session = session_date then tickets_retires else 0 end into ticket_deja
    from public.clients where id = p_client_ticket_id and actif for update;
    if not found then raise exception 'Un client actif est obligatoire pour les tickets'; end if;
    if ticket_deja + ticket_quantite > 2 then raise exception 'Quota de tickets insuffisant pour cette session'; end if;
  elsif p_client_ticket_id is not null then raise exception 'Aucun ticket présent dans le panier';
  end if;

  select coalesce(sum((element->>'quantite')::integer), 0) into expected_permits
  from jsonb_array_elements(p_lignes) element
  join public.catalogue article on article.id = (element->>'article_id')::bigint
  where article.type_article = 'document_permis';
  if jsonb_typeof(p_retraits_permis) <> 'array' or jsonb_array_length(p_retraits_permis) <> expected_permits then
    raise exception 'Chaque document de permis doit avoir un bénéficiaire';
  end if;
  if (select count(distinct (element->>'permit_id')) from jsonb_array_elements(p_retraits_permis) element) <> expected_permits then
    raise exception 'Un même dossier de permis ne peut être vendu qu’une fois';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(p_lignes) element
    join public.catalogue article on article.id = (element->>'article_id')::bigint
    where article.type_article = 'document_permis'
      and (element->>'quantite')::integer > 1
  ) then raise exception 'Un seul permis de chaque type peut être vendu par panier';
  end if;
  if exists (
    select 1
    from (
      select (element->>'article_id')::bigint article_id, (element->>'quantite')::integer quantite
      from jsonb_array_elements(p_lignes) element
      join public.catalogue article on article.id = (element->>'article_id')::bigint
      where article.type_article = 'document_permis'
    ) basket_permits
    full join (
      select (element->>'article_id')::bigint article_id, count(*)::integer quantite
      from jsonb_array_elements(p_retraits_permis) element
      group by 1
    ) assigned_permits using (article_id)
    where coalesce(basket_permits.quantite, 0) <> coalesce(assigned_permits.quantite, 0)
  ) then raise exception 'Chaque type de permis doit avoir exactement un bénéficiaire';
  end if;

  for retrait in
    select (element->>'article_id')::bigint article_id, (element->>'permit_id')::bigint permit_id
    from jsonb_array_elements(p_retraits_permis) element
  loop
    select type_article,
      case type_permis when 'Balais' then 'broomstick' when 'Moto' then 'motorcycle' when 'Voiture' then 'car' end
    into article_type, article_permit_type from public.catalogue where id = retrait.article_id;
    if article_type <> 'document_permis' then raise exception 'Article non lié à un permis'; end if;
    select * into permit from public.client_permits where id = retrait.permit_id for update;
    if not found or permit.type <> article_permit_type or permit.status <> 'accepted' then
      raise exception 'Ce document de permis ne peut pas être vendu';
    end if;
  end loop;

  total := public.enregistrer_vente(p_vendeur_id, p_lignes, 0, 'Vente');

  if ticket_quantite > 0 then
    update public.clients set tickets_retires = ticket_deja + ticket_quantite,
      ticket_session = session_date, updated_by = p_vendeur_id where id = p_client_ticket_id;
    perform public.journaliser_action_client(p_vendeur_id, 'withdraw_ticket', 'client', p_client_ticket_id::text,
      'ticket', p_client_ticket_id,
      jsonb_build_object('session', session_date, 'tickets_retires', ticket_deja),
      jsonb_build_object('session', session_date, 'tickets_retires', ticket_deja + ticket_quantite));
  end if;

  for retrait in
    select (element->>'permit_id')::bigint permit_id from jsonb_array_elements(p_retraits_permis) element
  loop
    select * into permit from public.client_permits where id = retrait.permit_id;
    update public.client_permits set status = 'sold' where id = permit.id;
    perform public.journaliser_action_client(p_vendeur_id, 'sell', 'client_permit', permit.id::text,
      'permit_' || permit.type, permit.client_id,
      jsonb_build_object('status', 'accepted'), jsonb_build_object('status', 'sold'));
  end loop;
  return total;
end;
$$;

