CREATE FUNCTION public.modifier_client(p_client_id bigint, p_nom_prenom text, p_hibou text, p_employe_id bigint) RETURNS bigint
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
declare client public.clients%rowtype; before_state jsonb;
begin
  if nullif(trim(p_nom_prenom), '') is null then raise exception 'Le nom du client est obligatoire'; end if;
  if not exists (select 1 from public.employes where id = p_employe_id and actif) then raise exception 'Employé introuvable ou inactif'; end if;
  select * into client from public.clients where id = p_client_id and actif for update;
  if not found then raise exception 'Client introuvable ou archivé'; end if;
  before_state := jsonb_build_object('nom_prenom', client.nom_prenom, 'hibou', client.hibou);
  update public.clients set
    nom_prenom = trim(p_nom_prenom),
    hibou = nullif(trim(p_hibou), ''),
    updated_by = p_employe_id
  where id = client.id;
  perform public.journaliser_action_client(p_employe_id, 'update', 'client', client.id::text,
    'client', client.id, before_state,
    jsonb_build_object('nom_prenom', trim(p_nom_prenom), 'hibou', nullif(trim(p_hibou), '')));
  return client.id;
exception when unique_violation then
  raise exception 'Ce hibou est déjà associé à un autre client';
end;
$$;

CREATE FUNCTION public.modifier_mot_de_passe_direction(p_employe_id bigint, p_nouveau_mot_de_passe text) RETURNS boolean
