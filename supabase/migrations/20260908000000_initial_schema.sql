CREATE FUNCTION public.creer_commande(p_client_id bigint, p_employe_id bigint, p_date_livraison date, p_lignes jsonb, p_contenu text DEFAULT NULL::text) RETURNS bigint
    LANGUAGE plpgsql
    SET search_path TO ''
    AS $$
declare
  commande_id bigint;
  ligne record;
  prix_article numeric;
begin
  if jsonb_typeof(p_lignes) <> 'array' or jsonb_array_length(p_lignes) = 0 then
    raise exception 'La commande doit contenir au moins une ligne';
  end if;
  if not exists (select 1 from public.clients where id = p_client_id and actif) then
    raise exception 'Client % introuvable ou inactif', p_client_id;
  end if;
  if not exists (select 1 from public.employes where id = p_employe_id and actif) then
    raise exception 'Employé % introuvable ou inactif', p_employe_id;
  end if;

  insert into public.commandes (client_id, employe_id, date_livraison, contenu)
  values (p_client_id, p_employe_id, p_date_livraison, nullif(trim(p_contenu), ''))
  returning id into commande_id;

  for ligne in
    select (element->>'article_id')::bigint as article_id,
           (element->>'quantite')::integer as quantite,
           nullif(element->>'prix_unitaire', '')::numeric as prix_unitaire
    from jsonb_array_elements(p_lignes) element
  loop
    if ligne.quantite is null or ligne.quantite <= 0 then
      raise exception 'Chaque quantité commandée doit être strictement positive';
    end if;
    select catalogue.prix_vente into prix_article
    from public.catalogue catalogue
    where catalogue.id = ligne.article_id and catalogue.actif;
    if not found then raise exception 'Article % introuvable ou inactif', ligne.article_id; end if;

    insert into public.lignes_commandes (commande_id, article_id, quantite, prix_unitaire)
    values (commande_id, ligne.article_id, ligne.quantite, coalesce(ligne.prix_unitaire, prix_article));
  end loop;
  return commande_id;
end;
$$;

CREATE FUNCTION public.decrementer_stock(p_article_id bigint, p_quantite integer) RETURNS void
    LANGUAGE plpgsql
    SET search_path TO ''
    AS $$
declare
  quantite_disponible integer;
begin
  if p_quantite <= 0 then
    raise exception 'La quantité à retirer doit être strictement positive';
  end if;

  select stock.quantite
  into quantite_disponible
  from public.stocks stock
  where stock.article_id = p_article_id
  for update;

  if quantite_disponible is null then
    raise exception 'Aucun stock trouvé pour l''article %', p_article_id;
  end if;

  if quantite_disponible < p_quantite then
    raise exception 'Stock insuffisant pour l''article % : % disponible(s), % demandé(s)',
      p_article_id, quantite_disponible, p_quantite;
  end if;

  update public.stocks
  set quantite = quantite - p_quantite,
      updated_at = now()
  where article_id = p_article_id;
end;
$$;

CREATE FUNCTION public.definir_reference_tresorerie(p_employe_id bigint, p_montant numeric) RETURNS boolean
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
declare
  v_montant_precedent numeric;
begin
  if not exists (
    select 1 from public.employes
    where id = p_employe_id and actif and grade in ('Patron', 'Co-Patron')
  ) then
    raise exception 'Accès réservé à la Direction';
  end if;
  if p_montant < 0 then raise exception 'Le montant du coffre ne peut pas être négatif'; end if;

  select solde_reference_tresorerie into v_montant_precedent
  from public.parametres_erp
  where id;

  update public.parametres_erp
  set solde_reference_tresorerie = p_montant,
      reference_tresorerie_at = statement_timestamp(),
      updated_at = now()
  where id;

  perform public.ecrire_journal_action(
    p_employe_id,
    'treasury_reference_updated',
    'tresorerie',
    'coffre',
    'Montant dans le coffre',
    jsonb_build_object('montant', v_montant_precedent),
    jsonb_build_object('montant', p_montant),
    jsonb_build_object('source', 'erp_settings')
  );
  return true;
end;
$$;

