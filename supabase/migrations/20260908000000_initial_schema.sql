  if p_fin_at > now() + interval '1 minute' then raise exception 'Une période ne peut pas être clôturée dans le futur'; end if;
  if jsonb_typeof(p_remunerations) <> 'array' then
    raise exception 'Les rémunérations doivent être un tableau JSON';
