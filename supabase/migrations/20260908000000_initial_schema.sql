      nombre_achats = v_achats,
      nombre_crafts = v_crafts,
      cloturee_at = now()
  where id = periode.id;

  for remuneration in
    select (element->>'employe_id')::bigint as employe_id,
      coalesce((element->>'prime')::numeric, 0) as prime,
      coalesce((element->>'total_paye')::numeric, 0) as total_paye
    from jsonb_array_elements(p_remunerations) element
  loop
    insert into public.archives_rh (
      periode_id, employe_id, employe_nom, ca_ventes, prime, total_paye
    )
    select periode.id, employe.id, employe.nom_prenom,
      coalesce(sum(transaction.prix_total), 0), remuneration.prime, remuneration.total_paye
    from public.employes employe
    left join public.transactions transaction
      on transaction.vendeur_id = employe.id
      and transaction.periode_id = periode.id
      and transaction.type_transaction in ('Vente', 'Vente Employé')
    where employe.id = remuneration.employe_id
    group by employe.id, employe.nom_prenom;
    if not found then raise exception 'Employé % introuvable pour l''archive RH', remuneration.employe_id; end if;
  end loop;

  update public.employes set prime_actuelle = 0 where prime_actuelle is distinct from 0;
  insert into public.periodes_comptables (date_debut, debut_at)
  values (
    ((p_fin_at + interval '1 minute') at time zone 'Europe/Madrid')::date,
    p_fin_at + interval '1 minute'
  );
  return periode.id;
end;
$$;

CREATE FUNCTION public.cloturer_periode_horodatee_avec_audit(p_employe_id bigint, p_fin_at timestamp with time zone DEFAULT now(), p_remunerations jsonb DEFAULT '[]'::jsonb, p_purger_audit boolean DEFAULT false, p_sauvegarde_confirmee boolean DEFAULT false) RETURNS jsonb
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
declare
  v_limite timestamptz := statement_timestamp();
  v_periode_id bigint;
  v_lignes_supprimees bigint := 0;
begin
  if not exists (
    select 1 from public.employes
    where id = p_employe_id and actif and grade in ('Patron', 'Co-Patron')
  ) then raise exception 'Seule la Direction peut clôturer une période'; end if;
  if p_purger_audit and not p_sauvegarde_confirmee then
    raise exception 'Confirmez la sauvegarde avant de purger le journal technique';
  end if;
  if p_purger_audit then
    delete from public.audit_row_changes where created_at < v_limite;
    get diagnostics v_lignes_supprimees = row_count;
  end if;

  v_periode_id := public.cloturer_periode_horodatee(p_fin_at, p_remunerations);
  if p_purger_audit then
    perform public.ecrire_journal_action(
      p_employe_id, 'purge_audit', 'periode_comptable', v_periode_id::text,
      'Purge du journal technique après sauvegarde confirmée', null,
      jsonb_build_object('lignes_supprimees', v_lignes_supprimees),
      jsonb_build_object('sauvegarde_confirmee', true)
    );
  end if;
  return jsonb_build_object('periode_id', v_periode_id, 'audit_rows_deleted', v_lignes_supprimees);
end;
$$;

CREATE FUNCTION public.cloturer_periode_horodatee_avec_audit(p_employe_id bigint, p_fin_at timestamp with time zone, p_remunerations jsonb, p_purger_audit boolean, p_sauvegarde_confirmee boolean, p_coffre_valide numeric) RETURNS jsonb
