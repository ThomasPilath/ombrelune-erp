CREATE FUNCTION public.mettre_a_jour_parametres_erp(p_employe_id bigint, p_taux_etudiant numeric, p_taux_adulte numeric, p_taux_co_patron numeric, p_taux_patron numeric, p_taux_taxe numeric, p_plafond_etudiant numeric, p_plafond_adulte numeric, p_plafond_co_patron numeric, p_plafond_patron numeric, p_prime_max numeric) RETURNS boolean
