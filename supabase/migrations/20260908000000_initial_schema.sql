CREATE FUNCTION public.enregistrer_panier(p_vendeur_id bigint, p_lignes jsonb, p_client_ticket_id bigint DEFAULT NULL::bigint, p_retraits_permis jsonb DEFAULT '[]'::jsonb) RETURNS numeric
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
declare
  session_date date := public.session_jeu();
  ticket_quantite integer;
  ticket_deja integer := 0;
  retrait record;
  permit public.client_permits%rowtype;
  article_type text;
  article_permit_type text;
  expected_permits integer;
  total numeric;
begin
  if not exists (select 1 from public.employes where id = p_vendeur_id and actif) then raise exception 'Employé introuvable ou inactif'; end if;
  if jsonb_typeof(p_lignes) <> 'array' or jsonb_array_length(p_lignes) = 0 then raise exception 'Le panier est vide'; end if;

  select coalesce(sum((element->>'quantite')::integer), 0) into ticket_quantite
  from jsonb_array_elements(p_lignes) element
  join public.catalogue article on article.id = (element->>'article_id')::bigint
  where article.type_article = 'ticket';

  if ticket_quantite > 0 then
    if ticket_quantite > 2 then raise exception 'Deux tickets maximum par client et par session'; end if;
    if p_client_ticket_id is null then raise exception 'Un client actif est obligatoire pour les tickets'; end if;
    perform pg_advisory_xact_lock(hashtextextended('ticket:' || p_client_ticket_id || ':' || session_date, 0));
    select case when ticket_session = session_date then tickets_retires else 0 end into ticket_deja
    from public.clients where id = p_client_ticket_id and actif for update;
    if not found then raise exception 'Un client actif est obligatoire pour les tickets'; end if;
    if ticket_deja + ticket_quantite > 2 then raise exception 'Quota de tickets insuffisant pour cette session'; end if;
  elsif p_client_ticket_id is not null then raise exception 'Aucun ticket présent dans le panier';
  end if;

  select coalesce(sum((element->>'quantite')::integer), 0) into expected_permits
  from jsonb_array_elements(p_lignes) element
  join public.catalogue article on article.id = (element->>'article_id')::bigint
  where article.type_article = 'document_permis';
  if jsonb_typeof(p_retraits_permis) <> 'array' or jsonb_array_length(p_retraits_permis) <> expected_permits then
    raise exception 'Chaque document de permis doit avoir un bénéficiaire';
  end if;
  if (select count(distinct (element->>'permit_id')) from jsonb_array_elements(p_retraits_permis) element) <> expected_permits then
    raise exception 'Un même dossier de permis ne peut être vendu qu’une fois';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(p_lignes) element
    join public.catalogue article on article.id = (element->>'article_id')::bigint
    where article.type_article = 'document_permis'
      and (element->>'quantite')::integer > 1
  ) then raise exception 'Un seul permis de chaque type peut être vendu par panier';
  end if;
  if exists (
    select 1
    from (
      select (element->>'article_id')::bigint article_id, (element->>'quantite')::integer quantite
      from jsonb_array_elements(p_lignes) element
      join public.catalogue article on article.id = (element->>'article_id')::bigint
      where article.type_article = 'document_permis'
    ) basket_permits
    full join (
      select (element->>'article_id')::bigint article_id, count(*)::integer quantite
      from jsonb_array_elements(p_retraits_permis) element
      group by 1
    ) assigned_permits using (article_id)
    where coalesce(basket_permits.quantite, 0) <> coalesce(assigned_permits.quantite, 0)
  ) then raise exception 'Chaque type de permis doit avoir exactement un bénéficiaire';
  end if;

  for retrait in
    select (element->>'article_id')::bigint article_id, (element->>'permit_id')::bigint permit_id
    from jsonb_array_elements(p_retraits_permis) element
  loop
    select type_article,
      case type_permis when 'Balais' then 'broomstick' when 'Moto' then 'motorcycle' when 'Voiture' then 'car' end
    into article_type, article_permit_type from public.catalogue where id = retrait.article_id;
    if article_type <> 'document_permis' then raise exception 'Article non lié à un permis'; end if;
    select * into permit from public.client_permits where id = retrait.permit_id for update;
    if not found or permit.type <> article_permit_type or permit.status <> 'accepted' then
      raise exception 'Ce document de permis ne peut pas être vendu';
    end if;
  end loop;

  total := public.enregistrer_vente(p_vendeur_id, p_lignes, 0, 'Vente');

  if ticket_quantite > 0 then
    update public.clients set tickets_retires = ticket_deja + ticket_quantite,
      ticket_session = session_date, updated_by = p_vendeur_id where id = p_client_ticket_id;
    perform public.journaliser_action_client(p_vendeur_id, 'withdraw_ticket', 'client', p_client_ticket_id::text,
      'ticket', p_client_ticket_id,
      jsonb_build_object('session', session_date, 'tickets_retires', ticket_deja),
      jsonb_build_object('session', session_date, 'tickets_retires', ticket_deja + ticket_quantite));
  end if;

  for retrait in
    select (element->>'permit_id')::bigint permit_id from jsonb_array_elements(p_retraits_permis) element
  loop
    select * into permit from public.client_permits where id = retrait.permit_id;
    update public.client_permits set status = 'sold' where id = permit.id;
    perform public.journaliser_action_client(p_vendeur_id, 'sell', 'client_permit', permit.id::text,
      'permit_' || permit.type, permit.client_id,
      jsonb_build_object('status', 'accepted'), jsonb_build_object('status', 'sold'));
  end loop;
  return total;
end;
$$;

CREATE FUNCTION public.enregistrer_panier_commandes(p_vendeur_id bigint, p_lignes jsonb, p_client_ticket_id bigint DEFAULT NULL::bigint, p_retraits_permis jsonb DEFAULT '[]'::jsonb, p_commande_ids jsonb DEFAULT '[]'::jsonb) RETURNS numeric
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
declare
  commande_id bigint;
  total numeric;
begin
  if jsonb_typeof(p_commande_ids) <> 'array' then
    raise exception 'La liste des commandes est invalide';
  end if;
  if (select count(*) from jsonb_array_elements_text(p_commande_ids)) <>
     (select count(distinct value) from jsonb_array_elements_text(p_commande_ids)) then
    raise exception 'Une commande ne peut être ajoutée qu’une fois au panier';
  end if;
  if exists (
    select 1 from jsonb_array_elements_text(p_commande_ids) element
    left join public.commandes commande on commande.id = element.value::bigint
    where commande.id is null or commande.statut_livraison <> 'Prêt'
  ) then
    raise exception 'Une commande du panier n’est plus prête à être vendue';
  end if;
  if exists (
    select 1
    from (
      select ligne.article_id, sum(ligne.quantite)::integer quantite
      from jsonb_array_elements_text(p_commande_ids) element
      join public.lignes_commandes ligne on ligne.commande_id = element.value::bigint
      group by ligne.article_id
    ) requis
    left join (
      select (element->>'article_id')::bigint article_id,
        sum((element->>'quantite')::integer)::integer quantite
      from jsonb_array_elements(p_lignes) element
      group by (element->>'article_id')::bigint
    ) panier using (article_id)
    where coalesce(panier.quantite, 0) < requis.quantite
  ) then
    raise exception 'Le panier ne contient pas toutes les lignes des commandes sélectionnées';
  end if;

  total := public.enregistrer_panier(p_vendeur_id, p_lignes, p_client_ticket_id, p_retraits_permis);

  for commande_id in select value::bigint from jsonb_array_elements_text(p_commande_ids)
  loop
    perform public.gerer_commande(commande_id, p_vendeur_id, 'Finalisation vente');
  end loop;
  return total;
end;
$$;

CREATE FUNCTION public.enregistrer_panier_employe(p_employe_id bigint, p_lignes jsonb, p_client_ticket_id bigint DEFAULT NULL::bigint) RETURNS numeric
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
declare
  session_date date := public.session_jeu();
  ticket_quantite integer;
  ticket_deja integer := 0;
  total numeric;
begin
  if not exists (select 1 from public.employes where id = p_employe_id and actif) then
    raise exception 'Employé introuvable ou inactif';
  end if;
  if jsonb_typeof(p_lignes) <> 'array' or jsonb_array_length(p_lignes) = 0 then
    raise exception 'Le panier est vide';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(p_lignes) element
    join public.catalogue article on article.id = (element->>'article_id')::bigint
    where article.type_article = 'document_permis'
  ) then
    raise exception 'Les documents de permis ne sont pas disponibles en achat employé';
  end if;

  select coalesce(sum((element->>'quantite')::integer), 0)
  into ticket_quantite
  from jsonb_array_elements(p_lignes) element
  join public.catalogue article on article.id = (element->>'article_id')::bigint
  where article.type_article = 'ticket';

  if ticket_quantite > 0 then
    if ticket_quantite > 2 then raise exception 'Deux tickets maximum par client et par session'; end if;
    if p_client_ticket_id is null then raise exception 'Un client actif est obligatoire pour les tickets'; end if;
    perform pg_advisory_xact_lock(hashtextextended('ticket:' || p_client_ticket_id || ':' || session_date, 0));
    select case when ticket_session = session_date then tickets_retires else 0 end
    into ticket_deja
    from public.clients
    where id = p_client_ticket_id and actif
    for update;
    if not found then raise exception 'Un client actif est obligatoire pour les tickets'; end if;
    if ticket_deja + ticket_quantite > 2 then raise exception 'Quota de tickets insuffisant pour cette session'; end if;
  elsif p_client_ticket_id is not null then
    raise exception 'Aucun ticket présent dans le panier';
  end if;

  total := public.enregistrer_achat_employe(p_employe_id, p_lignes);

  if ticket_quantite > 0 then
    update public.clients
    set tickets_retires = ticket_deja + ticket_quantite,
        ticket_session = session_date,
        updated_by = p_employe_id
    where id = p_client_ticket_id;
    perform public.journaliser_action_client(
      p_employe_id, 'withdraw_ticket', 'client', p_client_ticket_id::text,
      'ticket', p_client_ticket_id,
      jsonb_build_object('session', session_date, 'tickets_retires', ticket_deja),
      jsonb_build_object('session', session_date, 'tickets_retires', ticket_deja + ticket_quantite)
    );
  end if;

  return total;
end;
$$;

CREATE FUNCTION public.enregistrer_passage_permis_dossier(p_client_id bigint, p_type text, p_date_passage date, p_resultat text, p_tentatives integer, p_notes text, p_employe_id bigint) RETURNS bigint
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
declare
  permit public.client_permits%rowtype;
  permit_id bigint;
  next_status text;
  before_state jsonb;
begin
  if p_type not in ('broomstick', 'motorcycle', 'car') then raise exception 'Type de permis invalide'; end if;
  if p_resultat not in ('success', 'failure') then raise exception 'Résultat invalide'; end if;
  if p_tentatives < 1 then raise exception 'Le nombre de tentatives doit être supérieur à zéro'; end if;
  if not exists (select 1 from public.clients where id = p_client_id and actif) then raise exception 'Client introuvable ou archivé'; end if;
  if not exists (select 1 from public.employes where id = p_employe_id and actif) then raise exception 'Employé introuvable ou inactif'; end if;

  next_status := case when p_resultat = 'success' then 'accepted' else 'pending' end;
  select * into permit from public.client_permits
    where client_id = p_client_id and type = p_type for update;

  if found then
    if permit.status = 'sold' then raise exception 'Un permis vendu ne peut pas être modifié'; end if;
    before_state := to_jsonb(permit);
    update public.client_permits set
      status = next_status,
      passage_date = p_date_passage,
      attempts = p_tentatives,
      notes = coalesce(trim(p_notes), '')
    where id = permit.id returning id into permit_id;
    perform public.journaliser_action_client(p_employe_id, 'update_status', 'client_permit', permit_id::text,
      'permit_' || p_type, p_client_id, before_state,
      jsonb_build_object('status', next_status, 'passage_date', p_date_passage, 'attempts', p_tentatives, 'notes', coalesce(trim(p_notes), '')));
  else
    insert into public.client_permits (client_id, type, status, passage_date, attempts, notes)
    values (p_client_id, p_type, next_status, p_date_passage, p_tentatives, coalesce(trim(p_notes), ''))
    returning id into permit_id;
    perform public.journaliser_action_client(p_employe_id, 'create', 'client_permit', permit_id::text,
      'permit_' || p_type, p_client_id, null,
      jsonb_build_object('status', next_status, 'passage_date', p_date_passage, 'attempts', p_tentatives, 'notes', coalesce(trim(p_notes), '')));
  end if;
  return permit_id;
end;
$$;

CREATE FUNCTION public.enregistrer_rachat(p_employe_id bigint, p_lignes jsonb) RETURNS numeric
    LANGUAGE plpgsql
    SET search_path TO ''
    AS $$
declare
  ligne record;
  article public.catalogue%rowtype;
  cout_ligne numeric;
  total_rachat numeric := 0;
begin
  if not exists (select 1 from public.employes where id = p_employe_id and actif) then
    raise exception 'Employé % introuvable ou inactif', p_employe_id;
  end if;
  if jsonb_typeof(p_lignes) <> 'array' or jsonb_array_length(p_lignes) = 0 then
    raise exception 'Le rachat doit contenir au moins une ligne';
  end if;

  for ligne in
    select (element->>'article_id')::bigint as article_id,
           (element->>'quantite')::integer as quantite
    from jsonb_array_elements(p_lignes) element
    order by (element->>'article_id')::bigint
  loop
    if ligne.quantite is null or ligne.quantite <= 0 then
      raise exception 'Chaque quantité rachetée doit être strictement positive';
    end if;
    select * into article from public.catalogue where id = ligne.article_id and actif;
    if not found then raise exception 'Article % introuvable ou inactif', ligne.article_id; end if;

    cout_ligne := article.prix_achat * ligne.quantite;
    insert into public.transactions (
      vendeur_id, article_id, quantite, prix_unitaire, prix_total,
      benefice_total, type_transaction
    ) values (
      p_employe_id, article.id, ligne.quantite, article.prix_achat,
      -cout_ligne, -cout_ligne, 'Achat'
    );
    perform public.incrementer_stock(article.id, ligne.quantite);
    total_rachat := total_rachat + cout_ligne;
  end loop;

  return total_rachat;
end;
$$;

CREATE FUNCTION public.enregistrer_vente(p_vendeur_id bigint, p_lignes jsonb, p_remise_pourcent numeric DEFAULT 0, p_type_transaction text DEFAULT 'Vente'::text) RETURNS numeric
    LANGUAGE plpgsql
    SET search_path TO ''
    AS $$
declare
  ligne record;
  article public.catalogue%rowtype;
  total_ligne numeric;
  cout_ligne numeric;
  total_vente numeric := 0;
begin
  if not exists (select 1 from public.employes where id = p_vendeur_id and actif) then
    raise exception 'Employé % introuvable ou inactif', p_vendeur_id;
  end if;
  if jsonb_typeof(p_lignes) <> 'array' or jsonb_array_length(p_lignes) = 0 then
    raise exception 'La vente doit contenir au moins une ligne';
  end if;
  if p_remise_pourcent < 0 or p_remise_pourcent > 100 then raise exception 'Remise invalide'; end if;
  if p_type_transaction not in ('Vente', 'Vente Employé') then raise exception 'Type de vente invalide'; end if;

  for ligne in
    select (element->>'article_id')::bigint article_id, (element->>'quantite')::integer quantite
    from jsonb_array_elements(p_lignes) element
    order by (element->>'article_id')::bigint
  loop
    if ligne.quantite is null or ligne.quantite <= 0 then raise exception 'Quantité de vente invalide'; end if;
    select * into article from public.catalogue where id = ligne.article_id and actif;
    if not found or article.prix_vente <= 0 then raise exception 'Article % non vendable', ligne.article_id; end if;

    -- Le supplément boussole est une majoration tarifaire et non un article physique.
    if lower(article.article) <> lower('Supplément boussole') then
      perform public.decrementer_stock(article.id, ligne.quantite);
    end if;

    total_ligne := round(article.prix_vente * ligne.quantite * (100 - p_remise_pourcent) / 100);
    cout_ligne := public.cout_revient_article(article.id) * ligne.quantite;
    insert into public.transactions (vendeur_id, article_id, quantite, prix_unitaire, prix_total, benefice_total, type_transaction)
    values (p_vendeur_id, article.id, ligne.quantite, article.prix_vente, total_ligne, total_ligne - cout_ligne, p_type_transaction);
    total_vente := total_vente + total_ligne;
  end loop;
  return total_vente;
end;
$$;

CREATE FUNCTION public.fabriquer_article(p_employe_id bigint, p_article_id bigint, p_nombre_crafts integer) RETURNS integer
    LANGUAGE plpgsql
    SET search_path TO ''
    AS $$
declare
  v_produit public.catalogue%rowtype;
  v_employe_nom text;
  v_ingredient record;
  v_quantite_produite integer;
  v_fabrication_id bigint;
  v_cout_ingredients numeric := 0;
  v_cout_ligne numeric;
begin
  if p_nombre_crafts <= 0 then raise exception 'Le nombre de crafts doit être positif'; end if;

  select employe.nom_prenom
  into v_employe_nom
  from public.employes employe
  where employe.id = p_employe_id and employe.actif;
  if v_employe_nom is null then raise exception 'Employé introuvable ou inactif'; end if;

  select catalogue.*
  into v_produit
  from public.catalogue catalogue
  where catalogue.id = p_article_id and catalogue.actif;
  if not found then raise exception 'Produit introuvable ou inactif'; end if;

  select recette.quantite_produite * p_nombre_crafts
  into v_quantite_produite
  from public.recettes_craft recette
  where recette.produit_id = p_article_id
  order by recette.id
  limit 1;
  if v_quantite_produite is null then raise exception 'Aucune recette trouvée'; end if;

  insert into public.fabrications (
    employe_id, employe_nom, produit_id, produit_nom, nombre_crafts,
    quantite_produite, cout_craft_total
  ) values (
    p_employe_id, v_employe_nom, v_produit.id, v_produit.article, p_nombre_crafts,
    v_quantite_produite, v_produit.cout_craft_po * p_nombre_crafts
  ) returning id into v_fabrication_id;

  for v_ingredient in
    select recette.ingredient_id, catalogue.article,
      recette.quantite_requise * p_nombre_crafts as quantite
    from public.recettes_craft recette
    join public.catalogue catalogue on catalogue.id = recette.ingredient_id
    where recette.produit_id = p_article_id
    order by recette.ingredient_id
  loop
    perform public.decrementer_stock(v_ingredient.ingredient_id, v_ingredient.quantite);
    v_cout_ligne := public.cout_revient_article(v_ingredient.ingredient_id) * v_ingredient.quantite;
    v_cout_ingredients := v_cout_ingredients + v_cout_ligne;
    insert into public.fabrications_ingredients (
      fabrication_id, ingredient_id, ingredient_nom, quantite_consommee,
      cout_unitaire, cout_total
    ) values (
      v_fabrication_id, v_ingredient.ingredient_id, v_ingredient.article,
      v_ingredient.quantite, public.cout_revient_article(v_ingredient.ingredient_id),
      v_cout_ligne
    );
  end loop;

  perform public.incrementer_stock(p_article_id, v_quantite_produite);
  update public.fabrications
  set cout_ingredients = v_cout_ingredients,
    cout_total = v_cout_ingredients + public.fabrications.cout_craft_total
  where public.fabrications.id = v_fabrication_id;

  insert into public.transactions (
    vendeur_id, article_id, quantite, prix_total, benefice_total, type_transaction
  ) values (
    p_employe_id, p_article_id, v_quantite_produite,
    -(v_produit.cout_craft_po * p_nombre_crafts),
    -(v_produit.cout_craft_po * p_nombre_crafts), 'Frais de Craft'
  );

  return v_quantite_produite;
end;
$$;

CREATE FUNCTION public.gerer_commande(p_commande_id bigint, p_employe_id bigint, p_action text) RETURNS void
    LANGUAGE plpgsql
    SET search_path TO ''
    AS $$
declare
  commande public.commandes%rowtype;
  employe_nom text;
  prochain_statut text;
  snapshot jsonb;
begin
  select nom_prenom into employe_nom
  from public.employes where id = p_employe_id and actif;
  if employe_nom is null then raise exception 'Employé introuvable ou inactif'; end if;

  select * into commande from public.commandes where id = p_commande_id for update;
  if not found then raise exception 'Commande introuvable'; end if;

  snapshot := to_jsonb(commande) || jsonb_build_object(
    'lignes', coalesce((select jsonb_agg(to_jsonb(ligne) order by ligne.id)
      from public.lignes_commandes ligne where ligne.commande_id = commande.id), '[]'::jsonb)
  );

  if p_action = 'Préparation terminée' then
    if commande.statut_livraison <> 'En attente' then raise exception 'Transition de commande invalide'; end if;
    prochain_statut := 'Prêt';
    update public.commandes set statut_livraison = prochain_statut, date_pret = current_date where id = commande.id;
  elsif p_action = 'Finalisation vente' then
    if commande.statut_livraison <> 'Prêt' then raise exception 'Seule une commande prête peut être vendue'; end if;
    prochain_statut := 'Vendu';
    update public.commandes set statut_livraison = prochain_statut, statut_paiement = 'Payé' where id = commande.id;
  elsif p_action = 'Annulation' then
    if commande.statut_livraison in ('Vendu', 'Annulée') then raise exception 'Cette commande ne peut plus être annulée'; end if;
    prochain_statut := 'Annulée';
    update public.commandes set statut_avant_annulation = commande.statut_livraison,
      statut_livraison = prochain_statut where id = commande.id;
  elsif p_action = 'Restauration' then
    if commande.statut_livraison <> 'Annulée' then raise exception 'Seule une commande annulée peut être restaurée'; end if;
    prochain_statut := coalesce(commande.statut_avant_annulation, 'En attente');
    update public.commandes set statut_livraison = prochain_statut,
      statut_avant_annulation = null where id = commande.id;
  elsif p_action = 'Retour arrière' then
    if commande.statut_livraison <> 'Prêt' then raise exception 'Aucun état précédent disponible'; end if;
    prochain_statut := 'En attente';
    update public.commandes set statut_livraison = prochain_statut, date_pret = null where id = commande.id;
  elsif p_action = 'Suppression' then
    if commande.statut_livraison <> 'Annulée' then raise exception 'Une commande doit être annulée avant sa suppression'; end if;
    prochain_statut := null;
  else
    raise exception 'Action de commande invalide';
  end if;

  insert into public.commandes_journal (
    commande_id, commande_reference, employe_id, employe_nom, action,
    statut_avant, statut_apres, commande_snapshot
  ) values (
    commande.id, commande.id, p_employe_id, employe_nom, p_action,
    commande.statut_livraison, prochain_statut, snapshot
  );

  if p_action = 'Suppression' then delete from public.commandes where id = commande.id; end if;
end;
$$;

CREATE FUNCTION public.incrementer_stock(p_article_id bigint, p_quantite integer) RETURNS void
    LANGUAGE plpgsql
    SET search_path TO ''
    AS $$
begin
  if p_quantite <= 0 then
    raise exception 'La quantité à ajouter doit être strictement positive';
  end if;

  insert into public.stocks (article_id, quantite)
  values (p_article_id, p_quantite)
  on conflict (article_id) do update
  set quantite = public.stocks.quantite + excluded.quantite,
      updated_at = now();
end;
$$;

CREATE FUNCTION public.journaliser_action_client(p_employe_id bigint, p_action text, p_entite_type text, p_entite_id text, p_element text, p_client_id bigint, p_avant jsonb, p_apres jsonb, p_metadata jsonb DEFAULT '{}'::jsonb) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
declare v_employe_nom text;
begin
  select nom_prenom into v_employe_nom from public.employes where id = p_employe_id and actif;
  if v_employe_nom is null then raise exception 'Employé introuvable ou inactif'; end if;
  insert into public.journal_actions (
    employe_id, employe_nom, action, entite_type, entite_id, libelle,
    element, client_id, etat_avant, etat_apres, metadata
  ) values (
    p_employe_id, v_employe_nom, p_action, p_entite_type, p_entite_id,
    p_element, p_element, p_client_id, p_avant, p_apres, coalesce(p_metadata, '{}'::jsonb)
  );
end;
$$;

CREATE FUNCTION public.lister_journal_actions(p_page integer DEFAULT 1, p_page_size integer DEFAULT 25, p_recherche text DEFAULT ''::text, p_employe text DEFAULT ''::text, p_type text DEFAULT ''::text, p_action text DEFAULT ''::text, p_depuis date DEFAULT NULL::date, p_jusqu_a date DEFAULT NULL::date) RETURNS jsonb
    LANGUAGE sql STABLE
    SET search_path TO ''
    AS $$
  with filtered as (
    select action.*, client.nom_prenom as client_nom
    from public.journal_actions action
    left join public.clients client on client.id = action.client_id
    where (nullif(trim(p_recherche), '') is null or concat_ws(
      ' ', action.libelle, action.element, action.entite_id, client.nom_prenom
    ) ilike '%' || trim(p_recherche) || '%')
      and (nullif(p_employe, '') is null or action.employe_nom = p_employe)
      and (nullif(p_type, '') is null or action.entite_type = p_type)
      and (nullif(p_action, '') is null or action.action = p_action)
      and (p_depuis is null or action.created_at >= p_depuis::timestamptz)
      and (p_jusqu_a is null or action.created_at < (p_jusqu_a + 1)::timestamptz)
  ),
  page as (
    select filtered.*
    from filtered
    order by created_at desc, id desc
    limit least(greatest(p_page_size, 1), 100)
    offset (greatest(p_page, 1) - 1) * least(greatest(p_page_size, 1), 100)
  )
  select jsonb_build_object(
    'entries', coalesce((
      select jsonb_agg(
        (to_jsonb(page) - 'client_nom') || jsonb_build_object(
          'clients', case when page.client_nom is null then null else jsonb_build_object('nom_prenom', page.client_nom) end
        ) order by page.created_at desc, page.id desc
      )
      from page
    ), '[]'::jsonb),
    'total', (select count(*) from filtered),
    'employees', coalesce((select jsonb_agg(value order by value) from (select distinct employe_nom value from public.journal_actions where employe_nom is not null) distinct_values), '[]'::jsonb),
    'actions', coalesce((select jsonb_agg(value order by value) from (select distinct action value from public.journal_actions where action is not null) distinct_values), '[]'::jsonb),
    'entity_types', coalesce((select jsonb_agg(value order by value) from (select distinct entite_type value from public.journal_actions where entite_type is not null) distinct_values), '[]'::jsonb)
  );
$$;

CREATE FUNCTION public.lister_journal_actions_par_periode(p_page integer DEFAULT 1, p_page_size integer DEFAULT 25, p_recherche text DEFAULT ''::text, p_employe text DEFAULT ''::text, p_type text DEFAULT ''::text, p_action text DEFAULT ''::text, p_depuis date DEFAULT NULL::date, p_jusqu_a date DEFAULT NULL::date, p_periode_id bigint DEFAULT NULL::bigint) RETURNS jsonb
    LANGUAGE sql STABLE
    SET search_path TO ''
    AS $$
  with selected_period as (
    select debut_at, fin_at
    from public.periodes_comptables
    where id = p_periode_id
  ),
  filtered as (
    select action.*, client.nom_prenom as client_nom
    from public.journal_actions action
    left join public.clients client on client.id = action.client_id
    where (p_periode_id is null or exists (
        select 1 from selected_period periode
        where action.created_at >= periode.debut_at
          and (periode.fin_at is null or action.created_at <= periode.fin_at)
      ))
      and (nullif(trim(p_recherche), '') is null or concat_ws(
        ' ', action.libelle, action.element, action.entite_id, client.nom_prenom
      ) ilike '%' || trim(p_recherche) || '%')
      and (nullif(p_employe, '') is null or action.employe_nom = p_employe)
      and (nullif(p_type, '') is null or action.entite_type = p_type)
      and (nullif(p_action, '') is null or action.action = p_action)
      and (p_depuis is null or action.created_at >= p_depuis::timestamptz)
      and (p_jusqu_a is null or action.created_at < (p_jusqu_a + 1)::timestamptz)
  ),
  page as (
    select filtered.*
    from filtered
    order by created_at desc, id desc
    limit least(greatest(p_page_size, 1), 100)
    offset (greatest(p_page, 1) - 1) * least(greatest(p_page_size, 1), 100)
  )
  select jsonb_build_object(
    'entries', coalesce((
      select jsonb_agg(
        (to_jsonb(page) - 'client_nom') || jsonb_build_object(
          'clients', case when page.client_nom is null then null else jsonb_build_object('nom_prenom', page.client_nom) end
        ) order by page.created_at desc, page.id desc
      ) from page
    ), '[]'::jsonb),
    'total', (select count(*) from filtered),
    'employees', coalesce((select jsonb_agg(value order by value) from (select distinct employe_nom value from filtered where employe_nom is not null) values_list), '[]'::jsonb),
    'actions', coalesce((select jsonb_agg(value order by value) from (select distinct action value from filtered where action is not null) values_list), '[]'::jsonb),
    'entity_types', coalesce((select jsonb_agg(value order by value) from (select distinct entite_type value from filtered where entite_type is not null) values_list), '[]'::jsonb)
  );
