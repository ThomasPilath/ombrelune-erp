CREATE FUNCTION public.preparer_transaction() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO ''
    AS $$
declare
  debut_periode timestamptz;
begin
  new.periode_id := coalesce(new.periode_id, public.periode_comptable_ouverte_id());
  select debut_at into debut_periode
  from public.periodes_comptables
  where id = new.periode_id and statut = 'ouverte';
  if debut_periode is null then
    raise exception 'La transaction doit appartenir à une période ouverte';
  end if;
  if new.created_at < debut_periode then
    raise exception 'La transaction précède le début de la période comptable ouverte (%)', debut_periode;
  end if;

  new.date_transaction := (new.created_at at time zone 'Europe/Madrid')::date;
  if new.vendeur_id is not null then
    select nom_prenom into new.vendeur_nom from public.employes where id = new.vendeur_id;
  end if;
  if new.article_id is not null then
    select article into new.article_nom from public.catalogue where id = new.article_id;
  end if;
  return new;
end;
$$;

CREATE FUNCTION public.recalculer_total_commande() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO ''
    AS $$
declare
  id_commande bigint := coalesce(new.commande_id, old.commande_id);
begin
  update public.commandes
  set prix_total = coalesce((
    select sum(ligne.quantite * ligne.prix_unitaire)
    from public.lignes_commandes ligne
    where ligne.commande_id = id_commande
  ), 0)
  where id = id_commande;
  return coalesce(new, old);
end;
$$;

CREATE FUNCTION public.session_jeu(p_moment timestamp with time zone DEFAULT now()) RETURNS date
    LANGUAGE plpgsql STABLE
    SET search_path TO ''
    AS $$
declare
  moment_local timestamp := p_moment at time zone 'Europe/Madrid';
begin
  if moment_local::time >= time '15:00' then
    return moment_local::date;
  end if;
  return moment_local::date - 1;
end;
$$;

CREATE FUNCTION public.valider_passage_permis(p_permis_id bigint, p_employe_id bigint, p_statut text) RETURNS void
    LANGUAGE plpgsql
    SET search_path TO ''
    AS $$
begin
  if p_statut not in ('validé', 'interdit') then raise exception 'Statut de permis invalide'; end if;
  if not exists (select 1 from public.employes where id = p_employe_id and actif) then raise exception 'Employé invalide'; end if;
  update public.permis set statut = p_statut, valide_par = p_employe_id,
    resultat = case when p_statut = 'validé' then 'Admis' else 'Interdit' end
  where id = p_permis_id and statut is null;
  if not found then raise exception 'Permis introuvable ou déjà traité'; end if;
end;
$$;

CREATE FUNCTION public.verifier_acces_direction(p_employe_id bigint, p_mot_de_passe text) RETURNS boolean
