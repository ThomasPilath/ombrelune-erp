-- Schéma initial consolidé d’Ombrelune ERP.
-- À appliquer sur une base Supabase vide, puis charger supabase/seed.sql.
-- Les tables décrivent directement leur état final : aucun rattrapage de données
-- ni redéfinition successive de fonctions n’est nécessaire.
-- Les rôles anon/authenticated et les fonctions auth.* sont fournis par Supabase.

CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;

-- 1. Tables, identités et contraintes, dans l’ordre de leurs dépendances.

CREATE TABLE public.audit_row_changes (
    id bigint GENERATED ALWAYS AS IDENTITY,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    transaction_id bigint DEFAULT txid_current() NOT NULL,
    table_name text NOT NULL,
    operation text NOT NULL,
    record_id text,
    old_data jsonb,
    new_data jsonb,
    actor_role text,
    actor_id uuid,
    request_ip text,
    user_agent text,
    CONSTRAINT audit_row_changes_operation_check CHECK ((operation = ANY (ARRAY['INSERT'::text, 'UPDATE'::text, 'DELETE'::text]))),
    CONSTRAINT audit_row_changes_pkey PRIMARY KEY (id)
);

