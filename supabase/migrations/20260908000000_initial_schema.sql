CREATE TABLE public.periodes_comptables (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    date_debut date NOT NULL,
    date_fin date,
    statut text DEFAULT 'ouverte'::text NOT NULL,
    ca_total numeric(14,2) DEFAULT 0 NOT NULL,
    depenses numeric(14,2) DEFAULT 0 NOT NULL,
    benefice_brut numeric(14,2) DEFAULT 0 NOT NULL,
    taxes numeric(14,2) DEFAULT 0 NOT NULL,
    salaires_primes numeric(14,2) DEFAULT 0 NOT NULL,
    benefice_net numeric(14,2) DEFAULT 0 NOT NULL,
    nombre_ventes integer DEFAULT 0 NOT NULL,
    nombre_achats integer DEFAULT 0 NOT NULL,
    nombre_crafts integer DEFAULT 0 NOT NULL,
    cloturee_at timestamp with time zone,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    debut_at timestamp with time zone DEFAULT now() NOT NULL,
    fin_at timestamp with time zone,
    CONSTRAINT periodes_comptables_check CHECK (((date_fin IS NULL) OR (date_fin >= date_debut))),
    CONSTRAINT periodes_comptables_check1 CHECK ((((statut = 'ouverte'::text) AND (date_fin IS NULL) AND (cloturee_at IS NULL)) OR ((statut = 'clôturée'::text) AND (date_fin IS NOT NULL) AND (cloturee_at IS NOT NULL)))),
    CONSTRAINT periodes_comptables_horodatage_coherent CHECK ((((statut = 'ouverte'::text) AND (fin_at IS NULL)) OR ((statut = 'clôturée'::text) AND (fin_at IS NOT NULL) AND (fin_at >= debut_at)))),
    CONSTRAINT periodes_comptables_nombre_achats_check CHECK ((nombre_achats >= 0)),
    CONSTRAINT periodes_comptables_nombre_crafts_check CHECK ((nombre_crafts >= 0)),
    CONSTRAINT periodes_comptables_nombre_ventes_check CHECK ((nombre_ventes >= 0)),
    CONSTRAINT periodes_comptables_statut_check CHECK ((statut = ANY (ARRAY['ouverte'::text, 'clôturée'::text]))),
    CONSTRAINT periodes_comptables_horodatage_sans_chevauchement EXCLUDE USING gist (tstzrange(debut_at, COALESCE(fin_at, 'infinity'::timestamp with time zone), '[]'::text) WITH &&),
    CONSTRAINT periodes_comptables_pkey PRIMARY KEY (id)
);

